#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Supabase KeepAlive — Exécuteur GitHub Actions
---------------------------------------------
Automatise trois actions sur tes projets Supabase gratuits :
  - ping  : INSERT -> UPDATE -> COUNT -> DELETE (garde N lignes récentes)
  - setup : crée / répare la table dédiée + garde-fou 200 lignes via API de gestion
  - empty : vide toutes les lignes de la table de keep-alive (conserve la structure)

Aucune dépendance externe requise (bibliothèque standard Python uniquement).
"""
import argparse
import json
import os
import re
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from datetime import datetime, timezone

DEFAULT_TABLE = "keepalive_pings"
DEFAULT_KEEP = 5
MGMT_API = (os.environ.get("KEEPALIVE_MGMT_API") or "https://api.supabase.com").rstrip("/")
AUTO_SETUP_ON_PING = True
TABLE_RE = re.compile(r"^[A-Za-z0-9_\-]{1,63}$")
SETUP_PREFIXES = ("Table «", "Écriture refusée", "Colonne manquante")


def build_sql(table: str = DEFAULT_TABLE, variant: str = "anon") -> str:
    if not TABLE_RE.match(table):
        raise ValueError(f"Nom de table invalide : {table}")
    t = f'"{table}"'
    safe = re.sub(r"[^A-Za-z0-9_]", "_", table)
    is_default = table == DEFAULT_TABLE
    fn = "keepalive_cap" if is_default else f"keepalive_cap_{safe}"
    trg = "keepalive_cap_trg" if is_default else f"{fn}_trg"
    sql = f"""create table if not exists public.{t} (
  id bigint generated by default as identity primary key,
  label text check (char_length(label) <= 80),
  note text check (char_length(note) <= 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create or replace function public.{fn}() returns trigger
language plpgsql as $$
begin
  delete from public.{t}
  where id in (select id from public.{t} order by id desc offset 200);
  return null;
end $$;
drop trigger if exists {trg} on public.{t};
create trigger {trg} after insert on public.{t}
  for each statement execute function public.{fn}();

alter table public.{t} enable row level security;
drop policy if exists "keepalive_anon_all" on public.{t};
"""
    if variant != "secret":
        sql += f"""create policy "keepalive_anon_all" on public.{t}
  for all to anon, authenticated using (true) with check (true);
"""
    return sql + "notify pgrst, 'reload schema';\n"


def _request(method: str, url: str, key: str, body=None, extra=None):
    headers = {
        "apikey": key,
        "Accept": "application/json",
        "User-Agent": "SupabaseKeepAlive-GHActions/1.0",
    }
    if not key.startswith("sb_"):
        headers["Authorization"] = "Bearer " + key
    data = None
    if body is not None:
        data = json.dumps(body).encode("utf-8")
        headers["Content-Type"] = "application/json"
    if extra:
        headers.update(extra)
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.status, r.headers, r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.headers, e.read()


def describe_error(status: int, raw: bytes, table: str) -> str:
    msg, code = "", ""
    try:
        j = json.loads(raw.decode("utf-8", errors="replace"))
        if isinstance(j, dict):
            msg = str(j.get("message") or j.get("msg") or j.get("error") or "")
            code = str(j.get("code") or "")
    except Exception:
        pass
    low = msg.lower()
    if "invalid api key" in low or "jwt" in low or code in ("PGRST301", "PGRST300"):
        return "Clé API invalide ou expirée"
    if status in (401, 403) or code == "42501":
        return "Écriture refusée (RLS) : crée la table avec le bon SQL ou utilise une clé secrète"
    if status == 404 or code in ("PGRST205", "42P01"):
        return f"Table « {table} » introuvable"
    if code in ("PGRST204", "42703"):
        return "Colonne manquante : ré-exécute la création de table"
    if status >= 500:
        return f"Projet en pause ou indisponible (HTTP {status})"
    return f"HTTP {status} {msg[:100]}".strip()


def project_ref(url: str) -> str:
    host = (urllib.parse.urlparse(url or "").hostname or "").lower()
    return host.split(".")[0] if host.endswith(".supabase.co") else ""


def resolve_project(entry: dict) -> dict:
    url = (entry.get("url") or "").strip()
    if not url and entry.get("url_env"):
        url = (os.environ.get(entry["url_env"]) or "").strip()
    url = url.rstrip("/")

    key_env = (entry.get("key_env") or "").strip()
    key = (os.environ.get(key_env) or "").strip() if key_env else ""

    token_env = (entry.get("access_token_env") or "").strip()
    token = (os.environ.get(token_env) or "").strip() if token_env else ""

    return {
        "name": entry.get("name") or project_ref(url) or "projet",
        "account": entry.get("account") or "",
        "url": url,
        "key": key,
        "key_env": key_env,
        "key_type": entry.get("key_type") or "anon",
        "token": token,
        "token_env": token_env,
        "table": (entry.get("table") or DEFAULT_TABLE).strip(),
        "keep": max(1, min(150, int(entry.get("keep") or DEFAULT_KEEP))),
        "enabled": bool(entry.get("enabled", True)),
    }


def setup_table(p: dict):
    ref = project_ref(p["url"])
    if not ref:
        return False, "URL invalide pour la création auto (attendu : https://xxxx.supabase.co)"
    if not p["token"]:
        return False, f"Secret manquant : {p['token_env'] or 'access_token_env'}"

    sql = build_sql(p["table"], "secret" if p["key_type"] == "secret" else "anon")
    body = json.dumps({"query": sql}).encode("utf-8")
    req = urllib.request.Request(
        f"{MGMT_API}/v1/projects/{ref}/database/query",
        data=body,
        method="POST",
        headers={
            "Authorization": "Bearer " + p["token"],
            "Content-Type": "application/json",
            "Accept": "application/json",
            "User-Agent": "SupabaseKeepAlive-GHActions/1.0",
        },
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            st, raw = r.status, r.read()
    except urllib.error.HTTPError as e:
        st, raw = e.code, e.read()
    except urllib.error.URLError as e:
        return False, f"Connexion API Supabase impossible : {getattr(e, 'reason', e)}"

    if st in (200, 201):
        return True, f"Table « {p['table']} » créée / vérifiée"
    if st == 401:
        return False, "Jeton d'accès Supabase invalide ou expiré"
    if st == 403:
        return False, "Jeton sans droit sur ce projet (mauvais compte ?)"
    if st == 404:
        return False, f"Projet « {ref} » introuvable avec ce jeton"
    if st == 429:
        return False, "Trop de requêtes vers l'API Supabase"
    return False, f"Erreur API Supabase HTTP {st} : {raw.decode('utf-8', errors='replace')[:120]}"


def ping_project(p: dict):
    if not p["url"].startswith("http"):
        return False, "URL manquante ou invalide"
    if not p["key"]:
        return False, f"Secret manquant : {p['key_env']}"

    table = p["table"]
    keep = p["keep"]
    rest = f"{p['url']}/rest/v1/{urllib.parse.quote(table)}"
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    steps = []

    try:
        st, _hd, raw = _request(
            "POST",
            rest,
            p["key"],
            {"label": f"gh-ping {stamp}", "note": "GitHub Actions KeepAlive"},
            {"Prefer": "return=representation"},
        )
        if st not in (200, 201):
            return False, describe_error(st, raw, table)

        rows = json.loads(raw.decode("utf-8"))
        rid = rows[0]["id"]
        steps.append("INSERT OK")

        st, _hd, raw = _request(
            "PATCH",
            f"{rest}?id=eq.{rid}",
            p["key"],
            {"note": f"mis à jour {stamp}", "updated_at": stamp},
            {"Prefer": "return=minimal"},
        )
        steps.append("UPDATE OK" if st in (200, 204) else f"UPDATE KO ({describe_error(st, raw, table)})")

        st, hd, raw = _request(
            "GET",
            f"{rest}?select=id&order=id.asc&limit=1",
            p["key"],
            None,
            {"Prefer": "count=exact"},
        )
        total = None
        if st in (200, 206):
            tail = (hd.get("Content-Range") or "").split("/")[-1]
            total = int(tail) if tail.isdigit() else None

        if total is not None and total > keep:
            n = total - keep
            st, _hd, raw = _request("GET", f"{rest}?select=id&order=id.asc&limit={n}", p["key"])
            ids = [r["id"] for r in json.loads(raw.decode("utf-8"))] if st in (200, 206) else []
            if ids:
                ids_s = ",".join(str(i) for i in ids)
                st, _hd, raw = _request(
                    "DELETE",
                    f"{rest}?id=in.({ids_s})",
                    p["key"],
                    None,
                    {"Prefer": "return=minimal"},
                )
                if st in (200, 204):
                    steps.append(f"DELETE OK ({len(ids)})")
                    total = total - len(ids)
                else:
                    steps.append(f"DELETE KO ({describe_error(st, raw, table)})")

        if total is not None:
            steps.append(f"{total} ligne(s)")
        return True, "OK · " + " · ".join(steps)
    except urllib.error.URLError as e:
        return False, f"Connexion impossible : {getattr(e, 'reason', e)}"
    except Exception as e:
        return False, f"Erreur : {e}"


def empty_table(p: dict):
    if not p["url"].startswith("http"):
        return False, "URL manquante ou invalide"
    if not p["key"]:
        return False, f"Secret manquant : {p['key_env']}"

    table = p["table"]
    rest = f"{p['url']}/rest/v1/{urllib.parse.quote(table)}"
    try:
        before = None
        st, hd, raw = _request("GET", f"{rest}?select=id&limit=1", p["key"], None, {"Prefer": "count=exact"})
        if st in (200, 206):
            tail = (hd.get("Content-Range") or "").split("/")[-1]
            before = int(tail) if tail.isdigit() else None
        else:
            return False, describe_error(st, raw, table)

        st, _hd, raw = _request("DELETE", f"{rest}?id=not.is.null", p["key"], None, {"Prefer": "return=minimal"})
        if st not in (200, 204):
            return False, describe_error(st, raw, table)

        if before == 0:
            return True, f"Table « {table} » déjà vide"
        count_txt = f"{before} ligne(s) supprimée(s)" if before is not None else "lignes supprimées"
        return True, f"Table « {table} » vidée ({count_txt})"
    except urllib.error.URLError as e:
        return False, f"Connexion impossible : {getattr(e, 'reason', e)}"
    except Exception as e:
        return False, f"Erreur : {e}"


def write_summary(action: str, results: list):
    summary_path = os.environ.get("GITHUB_STEP_SUMMARY")
    if not summary_path:
        return
    lines = [
        f"## Supabase KeepAlive — {action}",
        "",
        "| Compte | Projet | Table | Résultat | Détail |",
        "| --- | --- | --- | --- | --- |",
    ]
    for item in results:
        badge = "OK" if item["ok"] else "ÉCHEC"
        lines.append(
            f"| {item['account'] or '—'} | {item['name']} | `{item['table']}` | {badge} | {item['message']} |"
        )
    lines.append("")
    with open(summary_path, "a", encoding="utf-8") as f:
        f.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description="Supabase KeepAlive GitHub Actions")
    parser.add_argument("action", choices=["ping", "setup", "empty"])
    parser.add_argument("--config", default="projects.json")
    parser.add_argument("--project", default="", help="Filtrer sur un nom de projet précis")
    parser.add_argument("--confirm", action="store_true", help="Requis pour empty")
    args = parser.parse_args()

    if args.action == "empty" and not args.confirm:
        print("Erreur : --confirm est requis pour vider les tables.", file=sys.stderr)
        sys.exit(2)

    with open(args.config, "r", encoding="utf-8") as f:
        data = json.load(f)

    raw_projects = data.get("projects", data) if isinstance(data, dict) else data
    projects = [resolve_project(e) for e in raw_projects]

    if args.project.strip():
        needle = args.project.strip().lower()
        projects = [p for p in projects if p["name"].lower() == needle]
    elif args.action == "ping":
        projects = [p for p in projects if p["enabled"]]

    if not projects:
        print("Aucun projet correspondant à traiter.")
        sys.exit(0)

    results = []
    for p in projects:
        if args.action == "ping":
            ok, msg = ping_project(p)
            if not ok and AUTO_SETUP_ON_PING and msg.startswith(SETUP_PREFIXES) and p["token"]:
                sok, smsg = setup_table(p)
                print(f"[{p['name']}] Auto-création table : {smsg}")
                if sok:
                    time.sleep(2)
                    ok, msg = ping_project(p)
                    if ok:
                        msg = msg.replace("OK · ", "OK · table créée · ", 1)
                else:
                    msg = f"{msg} · {smsg}"
        elif args.action == "setup":
            ok, msg = setup_table(p)
        else:
            ok, msg = empty_table(p)

        status_txt = "OK" if ok else "ECHEC"
        print(f"[{status_txt}] {p['name']} ({p['table']}) : {msg}")
        results.append({
            "name": p["name"],
            "account": p["account"],
            "table": p["table"],
            "ok": ok,
            "message": msg,
        })

    write_summary(args.action.upper(), results)
    if any(not r["ok"] for r in results):
        sys.exit(1)


if __name__ == "__main__":
    main()
