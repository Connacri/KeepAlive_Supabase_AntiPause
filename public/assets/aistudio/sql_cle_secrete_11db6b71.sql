-- Variante B : clé secrète (sb_secret_... / service_role). Plus sûr côté Supabase :
-- RLS activée SANS aucune policy => personne d'autre ne peut écrire dans la table.
create table if not exists public."keepalive_pings" (
  id bigint generated by default as identity primary key,
  label text check (char_length(label) <= 80),
  note text check (char_length(note) <= 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

-- Garde-fou : la table ne dépasse jamais 200 lignes
create or replace function public.keepalive_cap() returns trigger
language plpgsql as $$
begin
  delete from public."keepalive_pings"
  where id in (select id from public."keepalive_pings" order by id desc offset 200);
  return null;
end $$;
drop trigger if exists keepalive_cap_trg on public."keepalive_pings";
create trigger keepalive_cap_trg after insert on public."keepalive_pings"
  for each statement execute function public.keepalive_cap();

alter table public."keepalive_pings" enable row level security;
drop policy if exists "keepalive_anon_all" on public."keepalive_pings";
notify pgrst, 'reload schema';
