def make_handler(core: Core):
    class Handler(BaseHTTPRequestHandler):
        server_version = "KeepAlive"

        def log_message(self, *a):
            pass

        def _host_ok(self):
            host = (self.headers.get("Host") or "").rsplit(":", 1)[0].strip("[]")
            return host in ("127.0.0.1", "localhost", "::1")

        def _send(self, code, payload, ctype="application/json; charset=utf-8"):
            data = payload if isinstance(payload, bytes) else (
                payload.encode("utf-8") if isinstance(payload, str) else json.dumps(payload).encode("utf-8")
            )
            self.send_response(code)
            self.send_header("Content-Type", ctype)
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.send_header("X-Content-Type-Options", "nosniff")
            self.send_header("X-Frame-Options", "DENY")
            self.end_headers()
            self.wfile.write(data)

        def _body(self):
            n = int(self.headers.get("Content-Length") or 0)
            if n > 1_000_000:
                raise ValueError("Requête trop grande")
            return json.loads(self.rfile.read(n).decode("utf-8")) if n else {}

        def _authorized(self):
            return self._host_ok() and secrets.compare_digest(
                self.headers.get("X-Token") or "", core.web_token
            )

        def _route(self, method):
            if not self._host_ok():
                return self._send(403, {"error": "forbidden"})
            parsed = urllib.parse.urlparse(self.path)
            path = parsed.path
            if method == "GET" and path == "/":
                return self._send(200, INDEX_HTML.replace("__TOKEN__", core.web_token), "text/html; charset=utf-8")
            if not path.startswith("/api/"):
                return self._send(404, {"error": "not found"})
            if not self._authorized():
                return self._send(401, {"error": "non autorisé : recharge la page"})
            try:
                if method == "GET" and path == "/api/state":
                    return self._send(200, core.state())
                if method == "GET" and path == "/api/sql":
                    qs = urllib.parse.parse_qs(parsed.query)
                    v = qs.get("variant", ["anon"])[0]
                    t = qs.get("table", [DEFAULT_TABLE])[0]
                    if not TABLE_RE.match(t):
                        t = DEFAULT_TABLE
                    return self._send(200, {"sql": build_sql(t, "secret" if v == "secret" else "anon")})
                body = self._body() if method in ("POST", "PUT") else {}
                if method == "POST" and path == "/api/projects":
                    return self._send(200, core.public(core.add_project(body)))
                m = re.match(r"^/api/projects/([0-9a-f]{32})$", path)
                if m and method == "PUT":
                    return self._send(200, core.public(core.update_project(m.group(1), body)))
                if m and method == "DELETE":
                    core.delete_project(m.group(1))
                    return self._send(200, {"ok": True})
                m2 = re.match(r"^/api/projects/([0-9a-f]{32})/setup$", path)
                if m2 and method == "POST":
                    ok, msg = core.setup_project(m2.group(1))
                    return self._send(200, {"ok": ok, "message": msg})
                m3 = re.match(r"^/api/projects/([0-9a-f]{32})/empty$", path)
                if m3 and method == "POST":
                    if body.get("confirm") is not True:
                        raise ValueError("Confirmation requise")
                    ok, msg = core.empty_project(m3.group(1))
                    return self._send(200, {"ok": ok, "message": msg})
                if method == "POST" and path == "/api/empty":
                    if body.get("confirm") is not True:
                        raise ValueError("Confirmation requise")
                    res = core.empty_many()
                    return self._send(200, {"total": len(res), "ok_count": sum(1 for r in res if r[1]),
                                            "results": [{"name": n, "ok": o, "message": m_} for n, o, m_ in res]})
                if method == "POST" and path == "/api/ping":
                    pid = body.get("id")
                    core.ping_async([pid] if pid else None)
                    return self._send(200, {"ok": True})
                if method == "POST" and path == "/api/settings":
                    core.set_settings(body.get("interval_hours", 12), body.get("autostart", True), body.get("widget"))
                    return self._send(200, {"ok": True})
                if method == "POST" and path == "/api/import":
                    items = json.loads(body.get("text") or "[]")
                    added, errors = core.import_projects(items)
                    return self._send(200, {"added": added, "errors": errors})
                return self._send(404, {"error": "not found"})
            except (ValueError, TypeError) as e:
                return self._send(400, {"error": str(e)})
            except Exception as e:  # noqa: BLE001
                write_log(f"Erreur web : {e}")
                return self._send(500, {"error": "erreur interne"})

        def do_GET(self):
            self._route("GET")

        def do_POST(self):
            self._route("POST")

        def do_PUT(self):
            self._route("PUT")

        def do_DELETE(self):
            self._route("DELETE")

    return Handler


def start_web(core: Core):
    for port in range(WEB_PORT, WEB_PORT + 11):
        try:
            srv = ThreadingHTTPServer(("127.0.0.1", port), make_handler(core))
        except OSError:
            continue
        srv.daemon_threads = True
        core.web_port = port
        threading.Thread(target=srv.serve_forever, daemon=True).start()
        return srv
    return None


def open_web(core: Core):
    if core.web_port:
        webbrowser.open(f"http://127.0.0.1:{core.web_port}/")


