class Core:
    def __init__(self):
        self.cfg = load_config()
        self.lock = threading.RLock()
        self.ping_lock = threading.Lock()
        self.stop = threading.Event()
        self.events = queue.Queue()  # (kind, data) lus par la fenêtre Tk
        self.web_port = None
        self.web_token = secrets.token_urlsafe(24)
        self.busy = set()  # ids des projets en cours de ping (témoin bleu)

    # -- utilitaires
    def emit(self, kind, data=None):
        self.events.put((kind, data))

    def log(self, msg):
        write_log(msg)
        self.emit("log", msg)

    def save(self):
        with self.lock:
            save_config(self.cfg)

    def find(self, pid):
        with self.lock:
            return next((p for p in self.cfg["projects"] if p["id"] == pid), None)

    def public(self, p):
        def hint(k):
            return (k[:12] + "…") if k and len(k) > 14 else ("•••" if k else "")

