def project_ref(url: str) -> str:
    host = (urllib.parse.urlparse(url or "").hostname or "").lower()
    return host.split(".")[0] if host.endswith(".supabase.co") else ""


def sql_editor_url(url: str) -> str:
    ref = project_ref(url)
    return f"https://supabase.com/dashboard/project/{ref}/sql/new" if ref else "https://supabase.com/dashboard"


def setup_table(p: dict, token: str):
    """Exécute le SQL d'aide dans le projet. Retourne (ok, message)."""
    ref = project_ref(p.get("url", ""))
    if not ref:
        return False, "Création auto impossible : l'URL doit être de la forme https://xxxx.supabase.co"
    table = (p.get("table") or DEFAULT_TABLE).strip()
    variant = "secret" if p.get("secret_key") else "anon"
    body = json.dumps({"query": build_sql(table, variant)}).encode("utf-8")
    req = urllib.request.Request(
        f"{MGMT_API}/v1/projects/{ref}/database/query", data=body, method="POST",
        headers={"Authorization": "Bearer " + token, "Content-Type": "application/json",
                 "Accept": "application/json", "User-Agent": "SupabaseKeepAlive/3.0"},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            st, raw = r.status, r.read()
    except urllib.error.HTTPError as e:
        st, raw = e.code, e.read()
    except urllib.error.URLError as e:
        return False, f"Création de la table impossible : connexion à l'API Supabase ({getattr(e, 'reason', e)})"
    if st in (200, 201):
        return True, f"table « {table} » créée / vérifiée"
    detail = ""
    try:
        j = json.loads(raw.decode("utf-8", errors="replace"))
        detail = str(j.get("message") or j.get("error") or "") if isinstance(j, dict) else ""
    except Exception:
        pass
    if st == 401:
        return False, "Jeton d'accès Supabase invalide ou expiré (Dashboard > Account > Access Tokens)"
    if st == 403:
        return False, "Ce jeton d'accès n'a pas le droit de modifier ce projet (mauvais compte ?)"
    if st == 404:
        return False, f"Projet « {ref} » introuvable avec ce jeton (mauvais compte ?)"
    if st == 429:
        return False, "Trop de requêtes vers l'API Supabase : réessaie dans quelques minutes"
    return False, f"Création de la table refusée (HTTP {st}) {detail[:120]}".strip()


