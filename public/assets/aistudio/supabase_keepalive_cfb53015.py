def load_config() -> dict:
    cfg = json.loads(json.dumps(DEFAULT_CONFIG))
    try:
        with open(CONFIG_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        cfg.update({k: data[k] for k in ("interval_hours", "autostart", "projects", "widget") if k in data})
        w = dict(DEFAULT_WIDGET)
        w.update(cfg.get("widget") or {})
        cfg["widget"] = w
    except Exception:
        pass
    for p in cfg["projects"]:
        for f in SECRET_FIELDS:
            p[f] = unprotect(p.get(f, ""))
        p.setdefault("table", DEFAULT_TABLE)
        p.setdefault("keep", DEFAULT_KEEP)
    return cfg


def save_config(cfg: dict) -> None:
    out = json.loads(json.dumps(cfg))
    for p in out["projects"]:
        for f in SECRET_FIELDS:
            p[f] = protect(p.get(f, ""))
    tmp = CONFIG_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2, ensure_ascii=False)
    os.replace(tmp, CONFIG_PATH)


def write_log(msg: str) -> None:
    line = f"{datetime.now():%Y-%m-%d %H:%M:%S}  {msg}\n"
    try:
        if os.path.exists(LOG_PATH) and os.path.getsize(LOG_PATH) > 500_000:
            os.replace(LOG_PATH, LOG_PATH + ".old")
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(line)
    except Exception:
        pass


def tail_log(n: int = 30):
    try:
        with open(LOG_PATH, "rb") as f:
            f.seek(0, os.SEEK_END)
            size = f.tell()
            f.seek(max(0, size - 12000))
            data = f.read().decode("utf-8", errors="replace")
        return data.splitlines()[-n:]
    except Exception:
        return []


