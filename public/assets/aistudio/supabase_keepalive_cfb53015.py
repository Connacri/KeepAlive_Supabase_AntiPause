HEALTH_SHORT = {"ok": "OK", "warn": "Attention", "err": "Erreur", "busy": "Ping…", "new": "En attente", "off": "Désactivé"}


def health(p: dict, interval_h: float, now: float, busy: bool = False):
    """Retourne (niveau, libellé) avec niveau = ok | warn | err | busy | new | off."""
    if not p.get("enabled", True):
        return "off", "Désactivé"
    if busy:
        return "busy", "Ping en cours…"
    st = p.get("last_status", "") or ""
    if p.get("last_attempt") and not st.startswith("OK"):
        return "err", st or "Échec du dernier ping"
    ts = p.get("last_ok", 0)
    if not ts:
        return "new", "Pas encore pingé"
    age = now - ts
    if age > PAUSE_RISK_SEC:
        return "err", "Aucun succès depuis plus de 5 jours : risque de mise en pause"
    if age > interval_h * 3600 * 1.5:
        return "warn", "En retard sur le planning"
    if "✗" in st:
        return "warn", "OK, mais une étape a échoué : " + st
    return "ok", "OK"


