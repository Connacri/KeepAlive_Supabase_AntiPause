def acquire_single_instance():
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    try:
        s.bind(("127.0.0.1", LOCK_PORT))
        s.listen(5)
        return s
    except OSError:
        try:
            c = socket.create_connection(("127.0.0.1", LOCK_PORT), timeout=2)
            c.sendall(b"show")
            c.close()
        except Exception:
            pass
        return None


def listen_for_show(sock, core: Core):
    while not core.stop.is_set():
        try:
            conn, _ = sock.accept()
            conn.close()
            core.emit("show")
        except Exception:
            break


def main():
    args = set(sys.argv[1:])
    core = Core()

    if "--once" in args:  # Planificateur de tâches : un tour puis on quitte
        results = core.ping_many(None)
        for name, ok in results:
            print(("OK  " if ok else "ECHEC ") + name)
        sys.exit(0 if all(ok for _n, ok in results) else 1)

    lock_sock = acquire_single_instance()
    if lock_sock is None:
        return  # déjà lancé : on a demandé à l'autre instance de s'afficher

    if core.cfg.get("autostart", True):
        try:
            set_autostart(True)
        except Exception as e:  # noqa: BLE001
            write_log(f"Démarrage auto impossible : {e}")
    core.save()
    start_web(core)
    core.start_scheduler()
    threading.Thread(target=listen_for_show, args=(lock_sock, core), daemon=True).start()

    if "--headless" in args or not HAVE_TK:
        print(f"Interface web : http://127.0.0.1:{core.web_port}/  (Ctrl+C pour quitter)")
        try:
            while True:
                time.sleep(3600)
        except KeyboardInterrupt:
            return
    app = App(core, background="--background" in args)
    app.run()


if __name__ == "__main__":
    main()
