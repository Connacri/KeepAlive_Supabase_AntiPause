    # -- pings
    def ping_one(self, p):
        with self.lock:
            self.busy.add(p["id"])
        self.emit("refresh")
        try:
            ok, msg = ping_project(p)
            if not ok and needs_setup(msg):
                # Table absente / droits manquants : on la crée si on a un jeton d'accès
                tok = self.token_for(p)
                if tok:
                    sok, smsg = setup_table(p, tok)
                    self.log(f"[{self.label(p)}] {smsg}")
                    if sok:
                        time.sleep(2)  # rechargement du schéma PostgREST
                        ok, msg = ping_project(p)
                        if ok:
                            msg = msg.replace("OK · ", "OK · table créée · ", 1)
                    else:
                        msg = f"{msg} · {smsg}"
                else:
                    msg += " · (ou renseigne un jeton d'accès Supabase pour la créer automatiquement)"
            now = time.time()
            with self.lock:
                p["last_attempt"] = now
                p["last_status"] = msg
                if ok:
                    p["last_ok"] = now
                self.save()
            self.log(f"[{self.label(p)}] {msg}")
            return ok
        finally:
            with self.lock:
                self.busy.discard(p["id"])
            self.emit("refresh")

    def _empty_one(self, p):
        with self.lock:
            self.busy.add(p["id"])
        self.emit("refresh")
        try:
            ok, msg = empty_table(p)
            self.log(f"[{self.label(p)}] {msg}")
            if ok:
                with self.lock:  # le dernier statut ne doit plus afficher l'ancien nombre de lignes
                    st = p.get("last_status", "")
                    if st.startswith("OK") and re.search(r" · \d+ ligne\(s\)$", st):
                        p["last_status"] = re.sub(r" · \d+ ligne\(s\)$", " · 0 ligne(s) (vidée)", st)
                        self.save()
            return ok, msg
        finally:
            with self.lock:
                self.busy.discard(p["id"])
            self.emit("refresh")

    def empty_project(self, pid):
        """Vide la table d'UN projet (bloquant). Retourne (ok, message)."""
        p = self.find(pid)
        if not p:
            raise ValueError("Projet introuvable")
        with self.ping_lock:  # pas en même temps qu'un ping (qui réinsère une ligne)
            return self._empty_one(p)

    def empty_many(self, ids=None):
        """Vide la table de TOUS les projets (activés ou non) ou de ceux listés. Retourne [(nom, ok, msg)]."""
        with self.ping_lock:
            with self.lock:
                targets = [p for p in self.cfg["projects"] if (p["id"] in ids if ids else True)]
            out = []
            for p in targets:
                ok, msg = self._empty_one(p)
                out.append((p["name"], ok, msg))
            done = sum(1 for _n, ok, _m in out if ok)
            self.log(f"Vidage terminé : {done}/{len(out)} projet(s)")
            return out

    def ping_many(self, ids=None):
        """Bloquant. ids=None -> tous les projets actifs."""
        with self.ping_lock:
            with self.lock:
                targets = [
                    p for p in self.cfg["projects"]
                    if (p["id"] in ids if ids else p.get("enabled", True))
                ]
            return [(p["name"], self.ping_one(p)) for p in targets]

    def ping_async(self, ids=None):
        threading.Thread(target=self.ping_many, args=(ids,), daemon=True).start()

    def scheduler(self):
        time.sleep(15)  # laisse le réseau se connecter après le démarrage de Windows
        while not self.stop.is_set():
            try:
                with self.lock:
                    interval = max(1, int(self.cfg.get("interval_hours", 12))) * 3600
                    now = time.time()
                    due = [
                        p for p in self.cfg["projects"]
                        if p.get("enabled", True)
                        and now - p.get("last_ok", 0) >= interval
                        and now - p.get("last_attempt", 0) >= RETRY_AFTER_FAIL_SEC
                    ]
                if due and self.ping_lock.acquire(blocking=False):
                    try:
                        for p in due:
                            self.ping_one(p)
                    finally:
                        self.ping_lock.release()
            except Exception as e:  # noqa: BLE001
                write_log(f"Erreur planificateur : {e}")
            self.stop.wait(CHECK_EVERY_SEC)

    def start_scheduler(self):
        threading.Thread(target=self.scheduler, daemon=True).start()


