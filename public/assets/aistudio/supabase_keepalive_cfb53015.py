def build_sql(table: str = DEFAULT_TABLE, variant: str = "anon") -> str:
    """SQL (idempotent) qui crée la table de keep-alive + son garde-fou de 200 lignes."""
    t = '"%s"' % table  # TABLE_RE garantit [A-Za-z0-9_-] : sûr entre guillemets
    safe = re.sub(r"[^A-Za-z0-9_]", "_", table)
    default = table == DEFAULT_TABLE
    fn = "keepalive_cap" if default else "keepalive_cap_" + safe
    trg = "keepalive_cap_trg" if default else fn + "_trg"
    if variant == "secret":
        head = (
            "-- Variante B : clé secrète (sb_secret_... / service_role). Plus sûr côté Supabase :\n"
            "-- RLS activée SANS aucune policy => personne d'autre ne peut écrire dans la table.\n"
        )
    else:
        head = (
            "-- Variante A : clé publishable / anon (simple). Tout détenteur de la clé anon peut écrire\n"
            "-- dans CETTE table seulement (limitée à 200 lignes par le garde-fou).\n"
        )
    sql = head + f"""create table if not exists public.{t} (
  id bigint generated by default as identity primary key,
  label text check (char_length(label) <= 80),
  note text check (char_length(note) <= 200),
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

-- Garde-fou : la table ne dépasse jamais 200 lignes
create or replace function public.{fn}() returns trigger
language plpgsql as $$
begin
  delete from public.{t}
  where id in (select id from public.{t} order by id desc offset 200);
  return null;
end $$;
drop trigger if exists {trg} on public.{t};
create trigger {trg} after insert on public.{t}
  for each statement execute function public.{fn}();

alter table public.{t} enable row level security;
drop policy if exists "keepalive_anon_all" on public.{t};
"""
    if variant != "secret":
        sql += f"""create policy "keepalive_anon_all" on public.{t}
  for all to anon, authenticated using (true) with check (true);
"""
    return sql + "notify pgrst, 'reload schema';\n"


