class StepError(Exception):
    pass


def _request(method, url, key, body=None, extra=None):
    headers = {
        "apikey": key,
        "Accept": "application/json",
        "User-Agent": "SupabaseKeepAlive/3.0",
    }
    if not key.startswith("sb_"):  # anciennes clés JWT : aussi en Bearer
        headers["Authorization"] = "Bearer " + key
    data = None
    if body is not None:
        data = json.dumps(body).encode("utf-8")
        headers["Content-Type"] = "application/json"
    if extra:
        headers.update(extra)
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return r.status, r.headers, r.read()
    except urllib.error.HTTPError as e:
        return e.code, e.headers, e.read()


def describe_error(status: int, raw: bytes, table: str) -> str:
    msg, code = "", ""
    try:
        j = json.loads(raw.decode("utf-8", errors="replace"))
        if isinstance(j, dict):
            msg = str(j.get("message") or j.get("msg") or j.get("error") or "")
            code = str(j.get("code") or "")
    except Exception:
        pass
    low = msg.lower()
    if "invalid api key" in low or "jwt" in low or code in ("PGRST301", "PGRST300"):
        return "Clé API invalide ou expirée"
    if status in (401, 403) or code == "42501":
        return "Écriture refusée (RLS) : exécute le SQL d'aide du projet ou utilise la clé secrète"
    if status == 404 or code in ("PGRST205", "42P01"):
        return f"Table « {table} » introuvable : exécute le SQL d'aide dans Supabase"
    if code in ("PGRST204", "42703"):
        return "Colonne manquante : ré-exécute le SQL d'aide"
    if status >= 500:
        return f"Projet en pause ou indisponible (HTTP {status})"
    return f"HTTP {status} {msg[:90]}".strip()


def ping_project(p: dict):
    """Retourne (ok, message). ok = l'INSERT a réussi (vraie écriture en base)."""
    base = (p.get("url") or "").strip().rstrip("/")
    key = (p.get("secret_key") or p.get("anon_key") or "").strip()
    table = (p.get("table") or DEFAULT_TABLE).strip()
    keep = max(1, int(p.get("keep") or DEFAULT_KEEP))
    if not base.startswith("http") or not key:
        return False, "URL ou clé manquante"

    rest = f"{base}/rest/v1/{urllib.parse.quote(table)}"
    stamp = datetime.now(timezone.utc).isoformat(timespec="seconds")
    steps = []
    try:
        # 1) INSERT
        st, _hd, raw = _request(
            "POST", rest, key,
            {"label": f"ping {stamp}", "note": "créé par Supabase KeepAlive"},
            {"Prefer": "return=representation"},
        )
        if st not in (200, 201):
            return False, describe_error(st, raw, table)
        rows = json.loads(raw.decode("utf-8"))
        rid = rows[0]["id"]
        steps.append("INSERT ✓")

        # 2) UPDATE (modification de la ligne qu'on vient d'ajouter)
        st, _hd, raw = _request(
            "PATCH", f"{rest}?id=eq.{rid}", key,
            {"note": f"mis à jour {stamp}", "updated_at": stamp},
            {"Prefer": "return=minimal"},
        )
        steps.append("UPDATE ✓" if st in (200, 204) else f"UPDATE ✗ ({describe_error(st, raw, table)})")

        # 3) COUNT
        st, hd, raw = _request(
            "GET", f"{rest}?select=id&order=id.asc&limit=1", key, None, {"Prefer": "count=exact"}
        )
        total = None
        if st in (200, 206):
            cr = hd.get("Content-Range") or ""
            tail = cr.split("/")[-1]
            total = int(tail) if tail.isdigit() else None

        # 4) DELETE (les plus anciennes lignes au-delà de `keep`)
        if total is not None and total > keep:
            n = total - keep
            st, _hd, raw = _request("GET", f"{rest}?select=id&order=id.asc&limit={n}", key)
            ids = [r["id"] for r in json.loads(raw.decode("utf-8"))] if st in (200, 206) else []
            if ids:
                ids_s = ",".join(str(i) for i in ids)
                st, _hd, raw = _request(
                    "DELETE", f"{rest}?id=in.({ids_s})", key, None, {"Prefer": "return=minimal"}
                )
                steps.append(
                    f"DELETE ✓ ({len(ids)})" if st in (200, 204)
                    else f"DELETE ✗ ({describe_error(st, raw, table)})"
                )
            total = total - len(ids) if st in (200, 204) else total
        if total is not None:
            steps.append(f"{total} ligne(s)")
        return True, "OK · " + " · ".join(steps)
    except urllib.error.URLError as e:
        return False, f"Connexion impossible : {getattr(e, 'reason', e)}"
    except (KeyError, IndexError, ValueError, TypeError):
        return False, "Réponse inattendue du serveur (table sans colonne « id » ?)"
    except Exception as e:  # noqa: BLE001
        return False, f"Erreur : {e}"


def empty_table(p: dict):
    """Supprime TOUTES les lignes de la table de keep-alive du projet. Retourne (ok, message)."""
    base = (p.get("url") or "").strip().rstrip("/")
    key = (p.get("secret_key") or p.get("anon_key") or "").strip()
    table = (p.get("table") or DEFAULT_TABLE).strip()
    if not base.startswith("http") or not key:
        return False, "URL ou clé manquante"
    rest = f"{base}/rest/v1/{urllib.parse.quote(table)}"
    try:
        # nombre de lignes avant (pour le message) ; un échec ici n'empêche pas le vidage
        before = None
        st, hd, raw = _request("GET", f"{rest}?select=id&limit=1", key, None, {"Prefer": "count=exact"})
        if st in (200, 206):
            tail = (hd.get("Content-Range") or "").split("/")[-1]
            before = int(tail) if tail.isdigit() else None
        elif st not in (200, 206):
            return False, describe_error(st, raw, table)
        # PostgREST exige un filtre sur DELETE : « id non nul » = toutes les lignes
        st, _hd, raw = _request("DELETE", f"{rest}?id=not.is.null", key, None, {"Prefer": "return=minimal"})
        if st not in (200, 204):
            return False, describe_error(st, raw, table)
        if before == 0:
            return True, f"table « {table} » déjà vide"
        n = f"{before} ligne(s) supprimée(s)" if before is not None else "lignes supprimées"
        return True, f"table « {table} » vidée ({n})"
    except urllib.error.URLError as e:
        return False, f"Connexion impossible : {getattr(e, 'reason', e)}"
    except Exception as e:  # noqa: BLE001
        return False, f"Erreur : {e}"


