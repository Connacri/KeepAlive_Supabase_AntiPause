        def empty(self, selected_only):
            odd = "\n\n⚠ Nom de table inhabituel : vérifie que c'est bien la table de keep-alive."
            if selected_only:
                p = self.selected()
                if not p:
                    messagebox.showinfo(APP_TITLE, "Sélectionne un projet dans la liste.")
                    return
                tbl = p.get("table", DEFAULT_TABLE)
                if not messagebox.askyesno(
                        APP_TITLE, f"Vider la table « {tbl} » du projet « {p['name']} » ?\n\n"
                                   "Toutes ses lignes seront supprimées (aucune autre table n'est touchée)."
                                   + (odd if tbl != DEFAULT_TABLE else "")):
                    return
                ids = [p["id"]]
            else:
                with self.core.lock:
                    projs = list(self.core.cfg["projects"])
                if not projs:
                    return
                bad = [f"{p['name']} ({p.get('table')})" for p in projs if p.get("table", DEFAULT_TABLE) != DEFAULT_TABLE]
                if not messagebox.askyesno(
                        APP_TITLE, f"Vider la table de keep-alive des {len(projs)} projets ?\n\n"
                                   "Toutes leurs lignes seront supprimées (aucune autre table n'est touchée)."
                                   + (f"\n\n⚠ Tables au nom inhabituel : {', '.join(bad)}" if bad else "")):
                    return
