TABLE_RE = re.compile(r"^[A-Za-z0-9_\-]{1,63}$")
KEY_RE = re.compile(r"^[A-Za-z0-9_\-\.=+/]{10,}$")


def normalize_project(d: dict, existing: dict = None) -> dict:
    """Valide / nettoie. Pour une clé : absente (None) = inchangée, "" = effacée."""
    ex = existing or {}
    url = str(d.get("url", ex.get("url", "")) or "").strip().rstrip("/")
    for suf in ("/rest/v1", "/rest"):
        if url.endswith(suf):
            url = url[: -len(suf)].rstrip("/")
    if not re.match(r"^https?://[^/\s]+$", url):
        raise ValueError("URL invalide (exemple : https://xxxx.supabase.co)")

    keys = {}
    for f in SECRET_FIELDS:
        v = d.get(f)
        v = ex.get(f, "") if v is None else str(v).strip()
        if v and not KEY_RE.match(v):
            raise ValueError("Une clé contient des caractères invalides (copie-la sans espace ni retour à la ligne)")
        keys[f] = v
    if not keys["anon_key"] and not keys["secret_key"]:
        raise ValueError("Renseigne au moins la clé publishable / anon (ou la clé secrète)")

    table = str(d.get("table", ex.get("table", DEFAULT_TABLE)) or DEFAULT_TABLE).strip()
    if not TABLE_RE.match(table):
        raise ValueError("Nom de table invalide (lettres, chiffres, _ et - seulement)")
    try:
        keep = int(d.get("keep", ex.get("keep", DEFAULT_KEEP)) or DEFAULT_KEEP)
    except (TypeError, ValueError):
        raise ValueError("« Lignes à garder » doit être un nombre")
    keep = max(1, min(150, keep))
    account = str(d.get("account", ex.get("account", "")) or "").strip()[:120]
    name = str(d.get("name", ex.get("name", "")) or "").strip()[:80]
    if not name:
        name = urllib.parse.urlparse(url).hostname or "projet"
    enabled = d.get("enabled", ex.get("enabled", True))
    out = dict(ex)
    out.update(
        {"name": name, "account": account, "url": url, "table": table, "keep": keep,
         "enabled": bool(enabled), **keys}
    )
    return out


