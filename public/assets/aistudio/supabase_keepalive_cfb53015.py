        def import_json(self):
            path = filedialog.askopenfilename(title="Importer un config.json",
                                              filetypes=[("JSON", "*.json"), ("Tous", "*.*")])
            if not path:
                return
            try:
                with open(path, "r", encoding="utf-8") as f:
                    txt = re.sub(r"^\s*//.*$", "", f.read(), flags=re.M)  # tolère les commentaires //
                added, errors = self.core.import_projects(json.loads(txt))
                messagebox.showinfo(APP_TITLE, f"{added} projet(s) importé(s)." + ("\n\n" + "\n".join(errors) if errors else ""))
            except Exception as e:  # noqa: BLE001
                messagebox.showerror(APP_TITLE, f"Import impossible : {e}")

