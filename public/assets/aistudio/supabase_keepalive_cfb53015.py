        def start_tray(self):
            try:
                import pystray
                from PIL import Image, ImageDraw  # noqa: F401
            except Exception:
                return
            q = self.core.events
            menu = pystray.Menu(
                pystray.MenuItem("Ouvrir la fenêtre", lambda *_: q.put(("show", None)), default=True),
                pystray.MenuItem("Interface web", lambda *_: q.put(("web", None))),
                pystray.MenuItem("Afficher / masquer les témoins", lambda *_: q.put(("togglewidget", None))),
                pystray.MenuItem("Pinger maintenant", lambda *_: q.put(("pingall", None))),
                pystray.MenuItem("Quitter", lambda *_: q.put(("quit", None))),
            )
            self.tray = pystray.Icon(APP_NAME, self.tray_image("new"), APP_TITLE, menu)
            self.tray.run_detached()

        def update_tray(self):
            """Pastille de l'icône = pire état parmi les projets ; infobulle = nombre de projets OK."""
            if not self.tray:
                return
            counts, worst = self.core.summary()
            active = sum(counts[k] for k in ("ok", "warn", "err", "busy", "new"))
            try:
                if worst != self.tray_level:
                    self.tray.icon = self.tray_image(worst)
                    self.tray_level = worst
                self.tray.title = f"{APP_TITLE} — {counts['ok']}/{active} OK" if active else APP_TITLE
            except Exception:  # noqa: BLE001
                pass

        def on_close(self):
            self.root.withdraw() if self.tray else self.root.iconify()

        def show_window(self):
            self.root.deiconify()
            self.root.state("normal")
            self.root.lift()
            self.root.focus_force()

        def quit_app(self):
            self.core.stop.set()
            if self.tray:
                try:
                    self.tray.stop()
                except Exception:
                    pass
            self.root.destroy()

        def poll_events(self):
            try:
                while True:
                    kind, data = self.core.events.get_nowait()
                    if kind == "log":
                        self.append_log_ui(data)
                    elif kind == "refresh":
                        self.refresh_tree()
                        if self.widget is not None and self.widget.win.winfo_viewable():
                            self.widget.render()
                        self.update_tray()
                    elif kind == "widget":
                        self.apply_widget()
                    elif kind == "togglewidget":
                        cur = bool((self.core.cfg.get("widget") or {}).get("enabled", True))
                        self.core.set_widget(enabled=not cur)
                    elif kind == "show":
                        self.show_window()
                    elif kind == "web":
                        open_web(self.core)
                    elif kind == "pingall":
                        self.core.ping_async(None)
                    elif kind == "quit":
                        self.quit_app()
                        return
            except queue.Empty:
                pass
            self.root.after(300, self.poll_events)

        def run(self):
            self.root.mainloop()


